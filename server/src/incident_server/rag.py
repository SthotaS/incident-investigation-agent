"""Local embeddings and a FAISS index over seed cases and approved human decisions.

Only build_index downloads a model or writes index files. Searches use cached files.
The index directory must be trusted and generated by this application. Checksums
detect accidental damage; they do not make a third-party FAISS file safe to load.
"""

import argparse
import hashlib
import json
import os
from datetime import datetime
from functools import lru_cache
from importlib.resources import files
from pathlib import Path
from typing import Annotated, Any, Literal
from uuid import uuid4

from filelock import FileLock, Timeout
from incident_common.models import IncidentId, Record, Source, ToolResult, TransactionId
from incident_common.rag_models import RetrievalInfo, RetrievalMatch, SearchQuery
from pydantic import (
    AwareDatetime,
    BaseModel,
    ConfigDict,
    Field,
    TypeAdapter,
    ValidationError,
    model_validator,
)

EMBEDDING_MODEL = "BAAI/bge-small-en-v1.5"
EMBEDDING_DIMENSION = 384
INDEX_VERSION = "1"
MIN_SIMILARITY = 0.70
MAX_CASES = 1000
INDEX_FILE = "incidents.faiss"
METADATA_FILE = "metadata.json"
CURRENT_FILE = "current.json"
GENERATIONS_DIR = "generations"
BUILD_LOCK_FILE = ".build.lock"
BUILD_LOCK_TIMEOUT_SECONDS = 10
MAX_METADATA_BYTES = 65536
MAX_INDEX_BYTES = 4096 + MAX_CASES * EMBEDDING_DIMENSION * 4
TopK = Annotated[int, Field(strict=True, ge=1, le=5)]


class RagIndexError(RuntimeError):
    """Index preparation or search failed; this is not an empty search result."""


class HistoricalCase(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    incident_id: str = Field(pattern=r"^INC-[0-9]{5}$")
    title: str = Field(min_length=1, max_length=200)
    symptoms: str = Field(min_length=1, max_length=1500)
    service: str = Field(min_length=1, max_length=60)
    past_root_cause: str | None = Field(default=None, min_length=1, max_length=1000)
    useful_check: Literal["get_monitoring", "get_trace", "get_deployments"]
    check_reason: str = Field(min_length=1, max_length=500)
    resolved_at: AwareDatetime
    synthetic: Literal[True]
    reference: str
    human_decision: str | None = None
    action_taken: str | None = None
    outcome: str | None = None
    approved_by: str | None = None
    saved_at: datetime | None = None
    evidence_references: list[str] = Field(default_factory=list)
    record_source: Literal["synthetic_seed", "human_approved"] = "synthetic_seed"

    @model_validator(mode="after")
    def validate_case(self) -> "HistoricalCase":
        if self.reference != f"synthetic://incidents/{self.incident_id}":
            raise ValueError("The reference must match the synthetic incident ID.")
        return self

    def embedding_text(self) -> str:
        # Do not embed the known past cause or useful check into the search text.
        return f"Title: {self.title}\nSymptoms: {self.symptoms}\nService: {self.service}"


class IndexMetadata(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    index_version: Literal["1"] = INDEX_VERSION
    embedding_model: Literal["BAAI/bge-small-en-v1.5"] = EMBEDDING_MODEL
    dimension: Literal[384] = EMBEDDING_DIMENSION
    metric: Literal["cosine via normalized IndexFlatIP"] = "cosine via normalized IndexFlatIP"
    corpus_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    index_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    incident_ids: list[str] = Field(min_length=5, max_length=MAX_CASES)

    @property
    def fingerprint(self) -> str:
        return _sha256(_canonical_json(self.model_dump()))


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _canonical_json(value: object) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":")).encode("utf-8")


def load_seed_cases() -> tuple[HistoricalCase, ...]:
    resource = files("incident_server").joinpath("fixtures", "historical_incidents.json")
    try:
        cases = TypeAdapter(list[HistoricalCase]).validate_json(resource.read_text("utf-8"))
        if len(cases) != 5 or len({case.incident_id for case in cases}) != 5:
            raise ValueError("Exactly five distinct synthetic past incidents are required.")
        return tuple(cases)
    except (OSError, ValueError) as exc:
        raise RagIndexError("The packaged historical incidents are invalid.") from exc


def load_cases() -> tuple[HistoricalCase, ...]:
    """Read the five seeds plus durable, explicitly approved human decisions."""
    from incident_server.knowledge import DecisionStore, KnowledgeStoreError

    seeds = load_seed_cases()
    try:
        approved = DecisionStore().list(limit=MAX_CASES + 1)
        seed_ids = {case.incident_id for case in seeds}
        if any(record.incident_id in seed_ids for record in approved):
            raise RagIndexError("A saved decision conflicts with a packaged seed incident ID.")
        saved_cases = tuple(
            HistoricalCase(
                incident_id=record.incident_id,
                title=record.title,
                symptoms=record.symptoms,
                service=record.service,
                past_root_cause=record.confirmed_root_cause,
                useful_check=record.useful_check,
                check_reason=record.check_reason,
                resolved_at=record.occurred_at or record.saved_at,
                synthetic=record.synthetic,
                reference=f"synthetic://incidents/{record.incident_id}",
                human_decision=record.human_decision,
                action_taken=record.action_taken,
                outcome=record.outcome,
                approved_by=record.approved_by,
                saved_at=record.saved_at,
                evidence_references=record.evidence_references,
                record_source="human_approved",
            )
            for record in approved
        )
        cases = (*seeds, *saved_cases)
        if len(cases) > MAX_CASES:
            raise RagIndexError(f"The local capstone index supports at most {MAX_CASES} cases.")
        return cases
    except KnowledgeStoreError as exc:
        raise RagIndexError("The saved human-decision database could not be read.") from exc


def _corpus_hash(cases: tuple[HistoricalCase, ...]) -> str:
    return _sha256(_canonical_json([case.model_dump(mode="json") for case in cases]))


def get_index_path() -> Path:
    """Use a writable local project directory unless the caller supplies another."""
    return Path(os.environ.get("INCIDENT_RAG_DIR", "data/rag")).expanduser().resolve()


def _embedding_model(directory: Path, *, local_files_only: bool) -> Any:
    # Explicit model cache settings avoid mutating process-wide Hugging Face variables.
    from fastembed import TextEmbedding

    return TextEmbedding(
        model_name=EMBEDDING_MODEL,
        cache_dir=str(directory / "model-cache"),
        threads=2,
        providers=["CPUExecutionProvider"],
        local_files_only=local_files_only,
    )


def _normalized_vectors(values: Any, expected_rows: int) -> Any:
    import faiss
    import numpy as np

    vectors = np.ascontiguousarray(list(values), dtype=np.float32)
    if vectors.shape != (expected_rows, EMBEDDING_DIMENSION):
        raise RagIndexError("The embedding model returned an unexpected vector size.")
    if not np.isfinite(vectors).all() or (np.linalg.norm(vectors, axis=1) == 0).any():
        raise RagIndexError("The embedding model returned an invalid vector.")
    faiss.normalize_L2(vectors)
    return vectors


class GenerationManifest(BaseModel):
    """A single atomic pointer to a complete immutable index generation."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    version: Literal["1"] = "1"
    generation: str = Field(pattern=r"^[0-9a-f]{32}$")


def _read_bounded(path: Path, maximum: int) -> bytes:
    """Bound the actual read rather than relying on an earlier file-size check."""
    if path.is_symlink() or not path.is_file():
        raise ValueError("Index files must be regular local files, not symbolic links.")
    with path.open("rb") as stream:
        data = stream.read(maximum + 1)
    if len(data) > maximum:
        raise ValueError("Unexpectedly large local index file.")
    return data


def _index_files(directory: Path) -> tuple[Path, Path]:
    """Resolve a manifest once; an invalid manifest must never trigger legacy fallback."""
    manifest_path = directory / CURRENT_FILE
    if manifest_path.is_symlink():
        raise ValueError("The index manifest must not be a symbolic link.")
    try:
        manifest_bytes = _read_bounded(manifest_path, 4096)
    except ValueError:
        if not manifest_path.exists():
            # Existing installations keep working until an explicit rebuild creates a manifest.
            return directory / METADATA_FILE, directory / INDEX_FILE
        raise
    manifest = GenerationManifest.model_validate_json(manifest_bytes)
    generations = directory / GENERATIONS_DIR
    generation = generations / manifest.generation
    if generations.is_symlink() or generation.is_symlink() or not generation.is_dir():
        raise ValueError("The index generation must be a regular local directory.")
    return generation / METADATA_FILE, generation / INDEX_FILE


def _sync_directory(directory: Path) -> None:
    """Make published directory entries durable where directory fsync is supported."""
    if os.name == "nt":
        return
    descriptor = os.open(directory, os.O_RDONLY | getattr(os, "O_DIRECTORY", 0))
    try:
        os.fsync(descriptor)
    finally:
        os.close(descriptor)


def _atomic_write(path: Path, content: bytes) -> None:
    temporary = path.with_name(f".{path.name}.{uuid4().hex}.tmp")
    try:
        with temporary.open("xb") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        temporary.replace(path)
        _sync_directory(path.parent)
    finally:
        temporary.unlink(missing_ok=True)


def build_index(directory: Path | str | None = None, *, local_files_only: bool = False) -> Path:
    """Build one complete generation, then publish it with a single atomic pointer."""
    import faiss

    destination = Path(directory).expanduser().resolve() if directory else get_index_path()
    try:
        destination.mkdir(parents=True, exist_ok=True)
        lock_path = destination / BUILD_LOCK_FILE
        if lock_path.is_symlink():
            raise RagIndexError("The index build lock must not be a symbolic link.")
        with FileLock(str(lock_path), timeout=BUILD_LOCK_TIMEOUT_SECONDS):
            # Capture the corpus only after obtaining the cross-process build lock.
            cases = load_cases()
            corpus_hash = _corpus_hash(cases)
            model = _embedding_model(destination, local_files_only=local_files_only)
            vectors = _normalized_vectors(
                model.passage_embed([case.embedding_text() for case in cases]),
                len(cases),
            )
            index = faiss.IndexFlatIP(EMBEDDING_DIMENSION)
            index.add(vectors)
            binary = faiss.serialize_index(index).tobytes()
            metadata = IndexMetadata(
                corpus_sha256=corpus_hash,
                index_sha256=_sha256(binary),
                incident_ids=[case.incident_id for case in cases],
            )
            generations = destination / GENERATIONS_DIR
            if generations.is_symlink():
                raise RagIndexError("The index generations path must not be a symbolic link.")
            generations.mkdir(exist_ok=True)
            generation_id = uuid4().hex
            generation = generations / generation_id
            generation.mkdir()
            _atomic_write(generation / INDEX_FILE, binary)
            _atomic_write(generation / METADATA_FILE, metadata.model_dump_json(indent=2).encode())
            _sync_directory(generations)
            # A human save can commit while embeddings are being calculated. Never publish
            # that older snapshot over a more recent approved-decision corpus.
            if _corpus_hash(load_cases()) != corpus_hash:
                raise RagIndexError(
                    "Approved incidents changed during the index build. Run incident-index again."
                )
            manifest = GenerationManifest(generation=generation_id)
            if (destination / CURRENT_FILE).is_symlink():
                raise RagIndexError("The index manifest must not be a symbolic link.")
            _atomic_write(destination / CURRENT_FILE, manifest.model_dump_json(indent=2).encode())
            _cached_index.cache_clear()
            return destination
    except Timeout as exc:
        raise RagIndexError(
            "Another index build is running. Wait for it to finish, then try again."
        ) from exc
    except RagIndexError:
        raise
    except Exception as exc:
        raise RagIndexError("Index build failed. Check the download and local directory.") from exc


class IncidentIndex:
    def __init__(self, cases, metadata, index, model):
        self.cases: tuple[HistoricalCase, ...] = cases
        self.metadata: IndexMetadata = metadata
        self._index = index
        self._model = model

    @classmethod
    def load(cls, directory: Path | str) -> "IncidentIndex":
        """Validate a locally generated index before loading a cached CPU model."""
        import faiss
        import numpy as np

        directory = Path(directory).expanduser().resolve()
        cases = load_cases()
        try:
            metadata_file, index_file = _index_files(directory)
            metadata = IndexMetadata.model_validate_json(
                _read_bounded(metadata_file, MAX_METADATA_BYTES)
            )
            if metadata.corpus_sha256 != _corpus_hash(cases) or metadata.incident_ids != [
                case.incident_id for case in cases
            ]:
                raise ValueError("The index is stale for the seed cases and saved human decisions.")
            binary = _read_bounded(index_file, MAX_INDEX_BYTES)
            if _sha256(binary) != metadata.index_sha256:
                raise ValueError("The index checksum does not match.")
            # Decode the same bytes that were checked, avoiding a second file read.
            index = faiss.deserialize_index(np.frombuffer(binary, dtype=np.uint8).copy())
            if (
                not isinstance(index, faiss.IndexFlatIP)
                or index.d != EMBEDDING_DIMENSION
                or index.ntotal != len(cases)
                or index.metric_type != faiss.METRIC_INNER_PRODUCT
            ):
                raise ValueError("The index type, dimension, or record count is incorrect.")
            vectors = index.reconstruct_n(0, len(cases))
            if not np.isfinite(vectors).all() or not np.allclose(
                np.linalg.norm(vectors, axis=1), 1, atol=1e-5
            ):
                raise ValueError("The index vectors are not valid normalized vectors.")
            model = _embedding_model(directory, local_files_only=True)
            return cls(cases, metadata, index, model)
        except Exception as exc:
            raise RagIndexError(
                "RAG index or cached model is missing, stale, or damaged. Run incident-index first."
            ) from exc

    def search(
        self, query: str, top_k: int = 2, *, exclude_incident_id: str | None = None
    ) -> RetrievalInfo:
        query = TypeAdapter(SearchQuery).validate_python(query)
        top_k = TypeAdapter(TopK).validate_python(top_k)
        if exclude_incident_id is not None:
            exclude_incident_id = TypeAdapter(IncidentId).validate_python(exclude_incident_id)
        try:
            vector = _normalized_vectors(self._model.query_embed(query), 1)
            scores, positions = self._index.search(vector, min(len(self.cases), top_k + 1))
            matches = []
            for score, position in zip(scores[0], positions[0], strict=True):
                if position < 0 or float(score) < MIN_SIMILARITY:
                    continue
                case = self.cases[int(position)]
                if case.incident_id == exclude_incident_id:
                    continue
                matches.append(
                    RetrievalMatch(
                        incident_id=case.incident_id,
                        score=max(-1, min(1, float(score))),
                        reference=case.reference,
                    )
                )
                if len(matches) == top_k:
                    break
            return RetrievalInfo(
                query=query,
                embedding_model=EMBEDDING_MODEL,
                index_version=INDEX_VERSION,
                fingerprint=self.metadata.fingerprint,
                matches=matches,
            )
        except Exception as exc:
            raise RagIndexError(
                "The local vector search failed; no search result is available."
            ) from exc


@lru_cache(maxsize=2)
def _cached_index(directory: str, signature: tuple) -> IncidentIndex:
    return IncidentIndex.load(directory)


def get_index() -> IncidentIndex:
    directory = get_index_path()
    try:
        # Reload after a rebuild in a different process or a packaged-corpus change.
        metadata_file, index_file = _index_files(directory)
        stats = [path.stat() for path in (metadata_file, index_file)]
        signature = (
            str(metadata_file.parent),
            *((stat.st_mtime_ns, stat.st_size) for stat in stats),
            _corpus_hash(load_cases()),
        )
        return _cached_index(str(directory), signature)
    except (OSError, ValueError) as exc:
        raise RagIndexError(
            "The RAG index is missing or invalid. Run incident-index first."
        ) from exc


def search_similar_incidents(
    transaction_id: str,
    query: str,
    top_k: int = 2,
    *,
    current_incident_id: str | None = None,
) -> ToolResult:
    transaction_id = TypeAdapter(TransactionId).validate_python(transaction_id)
    index = get_index()
    retrieval = index.search(query, top_k, exclude_incident_id=current_incident_id)
    cases_by_id = {case.incident_id: case for case in index.cases}
    records = []
    for match in retrieval.matches:
        case = cases_by_id[match.incident_id]
        human_context = (
            f" Human decision: {case.human_decision} Action taken: {case.action_taken} "
            f"Outcome: {case.outcome}."
            if case.record_source == "human_approved"
            else ""
        )
        records.append(
            Record(
                record_id=f"history-{case.incident_id}",
                summary=(
                    f"Past synthetic {case.incident_id}: {case.title}. "
                    f"{case.check_reason}{human_context} "
                    "The past cause does not confirm the current cause."
                ),
                observed_at=case.resolved_at.isoformat(),
                reference=case.reference,
                facts={
                    "past_incident_id": case.incident_id,
                    "service": case.service,
                    "symptoms": case.symptoms,
                    "useful_check": case.useful_check,
                    "check_reason": case.check_reason,
                    "past_root_cause": case.past_root_cause,
                    "historical": True,
                    "record_source": case.record_source,
                    "human_decision": case.human_decision,
                    "action_taken": case.action_taken,
                    "outcome": case.outcome,
                    "approved_by": case.approved_by,
                    "saved_at": case.saved_at.isoformat() if case.saved_at else None,
                    "evidence_references": case.evidence_references,
                },
            )
        )
    return ToolResult(
        source=Source.HISTORY,
        transaction_id=transaction_id,
        status="found" if records else "empty",
        records=records,
        retrieval=retrieval,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Index seed incidents and saved human decisions.")
    parser.add_argument("--directory", type=Path, help="Defaults to INCIDENT_RAG_DIR or data/rag.")
    parser.add_argument(
        "--offline", action="store_true", help="Use only the cached embedding model"
    )
    args = parser.parse_args()
    try:
        destination = build_index(args.directory, local_files_only=args.offline)
    except (RagIndexError, ValidationError) as exc:
        parser.exit(1, f"{exc}\n")
    print(f"Indexed {len(load_cases())} synthetic incidents in {destination}")
    print(f"Embedding model: {EMBEDDING_MODEL}; dimensions: {EMBEDDING_DIMENSION}; CPU only.")


if __name__ == "__main__":
    main()
